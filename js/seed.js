const FALLBACK_ICON = { expense: '📦', income: '💰' };

export const SEED_COUNT = SEED_ROWS.length;

/**
 * 导入初始账单。
 * @param {boolean} force 手动触发时绕过「已导入」标记，但仍要求账本为空，避免重复导入。
 * @returns {{imported:number, reason:string}}
 */
export async function seedIfNeeded(force = false) {
  if (!force && await db.getMeta('seeded_oct2026')) {
    return { imported: 0, reason: 'already' };
  }

  const existing = await db.allRecords();
  if (existing.length > 0) {
    // 已有账单：不覆盖，并打标记，避免以后自动导入
    await db.setMeta('seeded_oct2026', true);
    return { imported: 0, reason: 'has-data' };
  }

  const cats = await db.listCategories();
  const rows = [];
  for (const [date, name, signed] of SEED_ROWS) {
    const type = signed < 0 ? 'expense' : 'income';
    let cat = cats.find((c) => c.type === type && c.name === name);
    if (!cat) {
      cat = await db.saveCategory({
        type,
        name,
        icon: FALLBACK_ICON[type],
        order: await db.nextCategoryOrder(type)
      });
      cats.push(cat);
    }
    rows.push({
      type,
      amount: Math.abs(signed),
      categoryId: cat.id,
      date,
      note: ''
    });
  }

  await db.addRecords(rows);
  await db.setMeta('seeded_oct2026', true);
  return { imported: rows.length, reason: 'imported' };
}
